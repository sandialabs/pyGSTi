_PP_UNNORMALIZED_1Q = None


def _pp1q_unnormalized():
    global _PP_UNNORMALIZED_1Q
    if _PP_UNNORMALIZED_1Q is None:
        _PP_UNNORMALIZED_1Q = _BuiltinBasis('PP', 4)  # *unnormalized* Pauli-product basis
    return _PP_UNNORMALIZED_1Q


def _normalize_errorgen_key(key):
    """Convert a user-facing error generator key into an `(errorgen_type, basis_element_labels)` pair."""
    if isinstance(key, _LEEL):
        return key.errorgen_type, tuple(key.basis_element_labels)
    if isinstance(key, _GEEL):
        raise ValueError("GlobalElementaryErrorgenLabel keys are ambiguous for the gadget; use local "
                         "labels / (type, pauli-string) tuples whose last character is the virtual qubit.")
    if hasattr(key, 'errorgen_type') and hasattr(key, 'basis_element_labels'):  # e.g. LocalStimErrorgenLabel
        bels = tuple(str(p)[1:].replace('_', 'I') if not isinstance(p, str) else p
                     for p in key.basis_element_labels)
        return key.errorgen_type, bels
    key = tuple(key)
    typ = key[0]
    if len(key) == 2 and isinstance(key[1], (tuple, list)):  # (type, (bel1[, bel2])) form
        bels = tuple(key[1])
    else:  # (type, bel1[, bel2]) form
        bels = tuple(key[1:])
    if typ not in ('H', 'S', 'C', 'A'):
        raise ValueError("Unrecognized error generator type '%s'" % str(typ))
    if typ in ('H', 'S') and len(bels) != 1 or typ in ('C', 'A') and len(bels) != 2:
        raise ValueError("Wrong number of basis element labels for error generator %s" % str(key))
    return typ, bels


def elementary_errorgen_matrix(errorgen_type, basis_element_labels, mx_basis='pp'):
    """
    Dense matrix of an elementary error generator with *unnormalized* Pauli basis elements.

    This matches the rate convention of :class:`LindbladErrorgen` and of the first-order sensitivity
    functions in :mod:`pygsti.tools.errgenproptools`.

    Parameters
    ----------
    errorgen_type : {'H', 'S', 'C', 'A'}
    basis_element_labels : tuple of str
        Pauli strings (all of the same length), one for 'H'/'S' and two for 'C'/'A'.
    mx_basis : Basis or str, optional
        Basis of the returned superoperator matrix.

    Returns
    -------
    numpy.ndarray
    """
    mx_std = _ot.create_elementary_errorgen_nqudit(errorgen_type, tuple(basis_element_labels), _pp1q_unnormalized())
    return _bt.change_basis(mx_std, 'std', mx_basis)


def mcm_gadget_errorgen(errorgen_rates, num_gadget_data_qubits=1, mx_basis='pp'):
    """
    Dense Lindbladian of the MCM gadget on (gadget data qubits + virtual qubit).

    Parameters
    ----------
    errorgen_rates : dict
        Maps error generator specifications to rates.  Keys may be ``(type, pauli)`` / ``(type, pauli1, pauli2)``
        tuples or :class:`LocalElementaryErrorgenLabel` objects, whose Pauli strings have length
        ``num_gadget_data_qubits + 1`` with the virtual qubit *last*.

    num_gadget_data_qubits : int, optional
        Number of data qubits the gadget acts on (1 for the standard single-qubit MCM gadget).

    mx_basis : Basis or str, optional
        Basis of the returned matrix.

    Returns
    -------
    numpy.ndarray
        A ``4**(k+1) x 4**(k+1)`` matrix, ``k = num_gadget_data_qubits``.
    """
    nq = num_gadget_data_qubits + 1
    L = _np.zeros((4**nq, 4**nq), dtype=complex)
    for key, rate in errorgen_rates.items():
        typ, bels = _normalize_errorgen_key(key)
        if any(len(b) != nq for b in bels):
            raise ValueError("Gadget error generator %s must have Pauli strings of length %d (data qubits + "
                             "virtual qubit)" % (str(key), nq))
        L += rate * elementary_errorgen_matrix(typ, bels, mx_basis)
    if _np.allclose(L.imag, 0):
        L = L.real
    return L


def _gadget_ops(num_gadget_data_qubits, measured_index):
    """(prep, cnot, {c: proj_c}) dense pp-basis operators for the gadget (virtual qubit last)."""
    k = num_gadget_data_qubits
    if not (0 <= measured_index < k):
        raise ValueError("measured_index must index one of the %d gadget data qubits" % k)
    ss = _QubitSpace(k + 1)
    # ideal CNOT from data qubit `measured_index` (control) to the virtual qubit (target)
    cnot_2q = _ot.unitary_to_superop(_itgs.standard_gatename_unitaries()['Gcnot'], 'pp')
    from pygsti.modelmembers.operations import EmbeddedOp as _EmbeddedOp, StaticArbitraryOp as _StaticArbitraryOp
    cnot = _EmbeddedOp(ss, (measured_index, k), _StaticArbitraryOp(cnot_2q, basis='pp')).to_dense()

    def superket(vec):
        return _bt.change_basis(_ot.state_to_dmvec(_np.array(vec, dtype=complex)), 'std', 'pp').real

    eye = _np.eye(4**k)
    prep = _np.kron(eye, superket([1, 0]).reshape(4, 1))
    proj = {'0': _np.kron(eye, superket([1, 0]).reshape(1, 4)),
            '1': _np.kron(eye, superket([0, 1]).reshape(1, 4))}
    return prep, cnot, proj


def mcm_gadget_crunch(gadget_superop, num_gadget_data_qubits=1, measured_index=0):
    """
    Apply the gadget's "crunch" map to a superoperator on (gadget data qubits + virtual qubit).

    Computes ``{c: (I ⊗ <<c|) E CNOT (I ⊗ |0>>)}`` for ``c in ('0', '1')``.  With ``E = exp(L)`` this
    gives the noisy instrument members; with ``E = L`` it gives the first-order instrument deviation.

    Parameters
    ----------
    gadget_superop : numpy.ndarray
        ``4**(k+1) x 4**(k+1)`` matrix in the pp basis (virtual qubit last).
    num_gadget_data_qubits : int, optional
    measured_index : int, optional
        Index (among the gadget data qubits) of the measured qubit = CNOT control.

    Returns
    -------
    dict
        Maps ``'0'`` and ``'1'`` to ``4**k x 4**k`` matrices (pp basis) on the gadget data qubits.
    """
    prep, cnot, proj = _gadget_ops(num_gadget_data_qubits, measured_index)
    return {c: proj[c] @ gadget_superop @ cnot @ prep for c in ('0', '1')}


def mcm_gadget_instrument_members(errorgen_rates, num_gadget_data_qubits=1, measured_index=0, first_order=False):
    """
    Dense (pp basis) members of the noisy instrument produced by the MCM gadget.

    Parameters
    ----------
    errorgen_rates : dict
        See :func:`mcm_gadget_errorgen`.  An empty dict gives the ideal projective instrument.
    num_gadget_data_qubits : int, optional
    measured_index : int, optional
        Index (among the gadget data qubits) of the measured qubit.
    first_order : bool, optional
        If True use ``I + L`` instead of ``exp(L)`` (the linearized instrument).

    Returns
    -------
    dict
        ``{'0': Q_0, '1': Q_1}`` with ``4**k x 4**k`` real matrices.
    """
    L = mcm_gadget_errorgen(errorgen_rates, num_gadget_data_qubits, 'pp')
    E = _np.eye(L.shape[0]) + L if first_order else _spl.expm(L)
    members = mcm_gadget_crunch(E, num_gadget_data_qubits, measured_index)
    return {c: (m.real if _np.allclose(m.imag, 0) else m) for c, m in members.items()}


def mcm_gadget_instrument(errorgen_rates, state_space, measured_qubit, gadget_qubits=None, evotype='default',
                          first_order=False):
    """
    Build a pyGSTi :class:`Instrument` for a noisy MCM from gadget error-generator rates.

    The instrument members are :class:`EmbeddedOp` (static) operators acting on the full `state_space`,
    so the instrument can be inserted directly into an n-qubit model, e.g.
    ``model.instrument_blks['layers'][Label('Iz', q)] = inst`` for local/cloud noise models (see
    :func:`insert_mcm_gadget_instrument`).

    Parameters
    ----------
    errorgen_rates : dict
        Gadget error generator rates; Pauli strings have length ``len(gadget_qubits) + 1`` with the
        virtual qubit last and the data qubits ordered as in `gadget_qubits`.
    state_space : StateSpace or QubitProcessorSpec or list
        The full state space of the model (or its qubit labels).
    measured_qubit : hashable
        Label of the measured qubit.
    gadget_qubits : list, optional
        Data qubits the gadget error generator acts on (must contain `measured_qubit`).  Defaults to
        ``[measured_qubit]``.
    evotype : Evotype or str, optional
    first_order : bool, optional
        If True the members are computed from ``I + L`` rather than ``exp(L)``.

    Returns
    -------
    Instrument
    """
    from pygsti.modelmembers.operations import EmbeddedOp as _EmbeddedOp, StaticArbitraryOp as _StaticArbitraryOp
    from pygsti.modelmembers.instruments import Instrument as _Instrument

    if isinstance(state_space, _StateSpace):
        ss = state_space
    elif hasattr(state_space, 'qubit_labels'):  # processor spec
        ss = _QubitSpace(state_space.qubit_labels)
    else:
        ss = _QubitSpace(list(state_space))

    gadget_qubits = [measured_qubit] if gadget_qubits is None else list(gadget_qubits)
    if measured_qubit not in gadget_qubits:
        raise ValueError("`gadget_qubits` must contain the measured qubit")
    members = mcm_gadget_instrument_members(errorgen_rates, len(gadget_qubits), gadget_qubits.index(measured_qubit),
                                            first_order=first_order)
    gadget_ss = _QubitSpace(gadget_qubits)
    inst_members = _collections.OrderedDict()
    for c, mx in members.items():
        local_op = _StaticArbitraryOp(mx, basis='pp', evotype=evotype, state_space=gadget_ss)
        if tuple(gadget_qubits) == tuple(ss.qubit_labels):
            inst_members[c] = local_op
        else:
            inst_members[c] = _EmbeddedOp(ss, tuple(gadget_qubits), local_op)
    return _Instrument(inst_members, evotype=evotype, state_space=ss)


def mcm_gadget_product_instrument(errorgen_rates_by_qubit, state_space, gadget_qubits_by_qubit=None,
                                  evotype='default', first_order=False):
    """
    Instrument for the simultaneous MCM of several qubits: the tensor product of single-qubit gadget instruments.

    Member keys are the concatenated single-qubit outcomes in the order of `errorgen_rates_by_qubit`
    (e.g. ``'01'``), matching pyGSTi's outcome convention for multi-qubit ``'Iz'`` instruments.

    Parameters
    ----------
    errorgen_rates_by_qubit : dict
        Maps each measured qubit label to its gadget error generator rates (see :func:`mcm_gadget_instrument`).
    state_space : StateSpace or QubitProcessorSpec or list
    gadget_qubits_by_qubit : dict, optional
        Maps measured qubits to the data qubits their gadget acts on (default: only the measured qubit).
    evotype : Evotype or str, optional
    first_order : bool, optional

    Returns
    -------
    Instrument
    """
    from pygsti.modelmembers.operations import ComposedOp as _ComposedOp
    from pygsti.modelmembers.instruments import Instrument as _Instrument
    measured = list(errorgen_rates_by_qubit.keys())
    gadget_qubits_by_qubit = {} if gadget_qubits_by_qubit is None else gadget_qubits_by_qubit
    single = {q: mcm_gadget_instrument(errorgen_rates_by_qubit[q], state_space, q, gadget_qubits_by_qubit.get(q, None),
                                       evotype=evotype, first_order=first_order) for q in measured}
    ss = next(iter(single.values())).state_space
    members = _collections.OrderedDict()
    for combo in _itertools.product('01', repeat=len(measured)):
        ops = [single[q][c].copy() for q, c in zip(measured, combo)]
        members[''.join(combo)] = _ComposedOp(ops, evotype=evotype, state_space=ss)
    return _Instrument(members, evotype=evotype, state_space=ss)


def insert_mcm_gadget_instrument(model, measured_qubit, errorgen_rates, gadget_qubits=None,
                                 mcm_gate_name=DEFAULT_MCM_GATE_NAMES[0], first_order=False):
    """
    Insert a gadget-generated noisy MCM instrument into a model under the label ``(mcm_gate_name, measured_qubit)``.

    Works for implicit (local/cloud noise) models via ``model.instrument_blks['layers']`` and for explicit
    models via ``model.instruments`` (in which case auto-embedding of the instruments dictionary is disabled
    since the constructed instrument already acts on the full state space).

    .. note::
       pyGSTi's map forward simulator cannot currently create layouts for implicit models containing
       instruments; use ``simulator='matrix'`` when constructing models that will be simulated with MCMs.

    Parameters
    ----------
    model : Model
    measured_qubit : hashable or tuple
        The measured qubit, or a tuple of qubits for a simultaneous multi-qubit measurement (in which case
        `errorgen_rates` must be a dict mapping each qubit to its gadget rates, see
        :func:`mcm_gadget_product_instrument`).
    errorgen_rates : dict
        See :func:`mcm_gadget_instrument`.
    gadget_qubits : list or dict, optional
    mcm_gate_name : str, optional
    first_order : bool, optional

    Returns
    -------
    Instrument
        The inserted instrument.
    """
    if isinstance(measured_qubit, (tuple, list)):
        inst = mcm_gadget_product_instrument({q: errorgen_rates[q] for q in measured_qubit}, model.state_space,
                                             gadget_qubits, evotype=model.evotype, first_order=first_order)
        key = _Label(mcm_gate_name, tuple(measured_qubit))
    else:
        inst = mcm_gadget_instrument(errorgen_rates, model.state_space, measured_qubit, gadget_qubits,
                                     evotype=model.evotype, first_order=first_order)
        key = _Label(mcm_gate_name, (measured_qubit,))
    if hasattr(model, 'instrument_blks'):
        if 'layers' not in model.instrument_blks:
            from pygsti.models.memberdict import OrderedMemberDict as _OrderedMemberDict
            model.instrument_blks['layers'] = _OrderedMemberDict(model, None, None, {})
        model.instrument_blks['layers'][key] = inst
    else:
        model.instruments.flags['auto_embed'] = False
        model.instruments[key] = inst
    return inst


