# Circuit-level gadget substitution
# ---------------------------------------------------------------------------------------------------

def is_mcm_label(lbl, mcm_gate_names=DEFAULT_MCM_GATE_NAMES):
    """
    Whether a (component) label denotes a mid-circuit measurement.

    Parameters
    ----------
    lbl : Label
        A circuit-layer component label.

    mcm_gate_names : iterable of str, optional
        The instrument names to treat as computational-basis mid-circuit measurements.

    Returns
    -------
    bool
    """
    return getattr(lbl, 'name', None) in mcm_gate_names


def mcm_infos(circuit, mcm_gate_names=DEFAULT_MCM_GATE_NAMES, virtual_labels=None):
    """
    Enumerate the mid-circuit measurements of a circuit (one record per measured qubit).

    Parameters
    ----------
    circuit : Circuit
        The circuit to inspect.

    mcm_gate_names : iterable of str, optional
        The instrument names to treat as computational-basis mid-circuit measurements.

    virtual_labels : list, optional
        Line labels to use for the virtual qubits (one per measured qubit, in MCM order).  If
        None they are generated by :func:`virtual_qubit_labels`.

    Returns
    -------
    list of MCMInfo
    """
    line_labels = circuit.line_labels
    infos = []
    for layer_index, layer_lbl in enumerate(circuit):
        for component_index, comp in enumerate(layer_lbl.components):
            if not is_mcm_label(comp, mcm_gate_names):
                continue
            qubits = comp.sslbls if comp.sslbls is not None else tuple(line_labels)
            for q in qubits:
                infos.append(MCMInfo(layer_index, component_index, len(infos), q, None))
    if virtual_labels is None:
        virtual_labels = virtual_qubit_labels(line_labels, len(infos))
    assert len(virtual_labels) >= len(infos), "Not enough virtual qubit labels supplied!"
    return [info._replace(virtual_qubit=virtual_labels[info.mcm_index]) for info in infos]


def num_mcms(circuit, mcm_gate_names=DEFAULT_MCM_GATE_NAMES):
    """
    The number of measured qubits in mid-circuit measurements of `circuit` (= number of virtual qubits).

    Parameters
    ----------
    circuit : Circuit
    mcm_gate_names : iterable of str, optional

    Returns
    -------
    int
    """
    count = 0
    for layer_lbl in circuit:
        for comp in layer_lbl.components:
            if is_mcm_label(comp, mcm_gate_names):
                count += len(comp.sslbls) if comp.sslbls is not None else len(circuit.line_labels)
    return count


def virtual_qubit_labels(line_labels, num_virtual):
    """
    Generate line labels for virtual qubits that do not collide with the given data-qubit labels.

    If all data labels are integers the virtual labels are the next unused integers, otherwise
    they are strings of the form ``'v0', 'v1', ...`` (skipping any that are already in use).

    Parameters
    ----------
    line_labels : tuple
        The data-qubit line labels.

    num_virtual : int
        The number of virtual qubit labels to generate.

    Returns
    -------
    list
    """
    if num_virtual == 0:
        return []
    existing = set(line_labels)
    if len(line_labels) > 0 and all(isinstance(l, (int, _np.integer)) for l in line_labels):
        start = max(int(l) for l in line_labels) + 1
        return [start + k for k in range(num_virtual)]
    labels = []
    k = 0
    while len(labels) < num_virtual:
        cand = '%s%d' % (VIRTUAL_QUBIT_TOKEN, k)
        if cand not in existing:
            labels.append(cand)
        k += 1
    return labels


def expand_mcm_circuit(circuit, mcm_gate_names=DEFAULT_MCM_GATE_NAMES, cnot_name='Gcnot',
                       virtual_labels=None):
    """
    Replace every mid-circuit measurement by a CNOT onto a fresh virtual qubit (deferred measurement).

    Each measured qubit ``q`` of an instrument label in `circuit` is replaced by ``Label(cnot_name, (q, v))``
    where ``v`` is a new virtual qubit line appended after the data qubits.  The measurement of ``v`` is
    deferred to the end of the circuit, so the terminating computational-basis measurement of the
    returned circuit yields the joint distribution of the original circuit's final bitstring and MCM
    outcomes (see :func:`joint_outcome_to_bitstring` for the bit ordering).

    Parameters
    ----------
    circuit : Circuit
        A circuit whose layers may contain instrument labels (e.g. ``Label('Iz', 0)``).  Circuits
        containing :class:`CircuitLabel` sub-circuits are not supported.

    mcm_gate_names : iterable of str, optional
        Instrument names treated as computational-basis mid-circuit measurements.

    cnot_name : str, optional
        Name of the (ideal) controlled-NOT gate used in the gadget.

    virtual_labels : list, optional
        Line labels for the virtual qubits; generated by :func:`virtual_qubit_labels` if None.

    Returns
    -------
    expanded_circuit : Circuit
        Clifford circuit on ``n + m`` lines (data lines first, then virtual lines in MCM order).
    infos : list of MCMInfo
        One record per measured qubit, in MCM order (= virtual-qubit order).
    """
    infos = mcm_infos(circuit, mcm_gate_names, virtual_labels)
    new_line_labels = tuple(circuit.line_labels) + tuple(info.virtual_qubit for info in infos)
    if len(infos) == 0:
        return circuit.copy(editable=False), infos

    info_iter = iter(infos)
    new_layers = []
    for layer_index, layer_lbl in enumerate(circuit):
        if isinstance(layer_lbl, _CircuitLabel) or any(isinstance(c, _CircuitLabel) for c in layer_lbl.components):
            raise NotImplementedError("Circuits with CircuitLabel sub-circuits are not supported by "
                                      "expand_mcm_circuit; expand them first.")
        new_components = []
        for comp in layer_lbl.components:
            if is_mcm_label(comp, mcm_gate_names):
                qubits = comp.sslbls if comp.sslbls is not None else tuple(circuit.line_labels)
                for q in qubits:
                    info = next(info_iter)
                    assert info.data_qubit == q and info.layer_index == layer_index
                    new_components.append(_Label(cnot_name, (q, info.virtual_qubit)))
            else:
                new_components.append(comp)
        if len(new_components) == 1:
            new_layers.append(new_components[0])
        else:
            new_layers.append(_Label(new_components))
    return _Circuit(new_layers, line_labels=new_line_labels), infos


def joint_outcome_to_bitstring(outcome):
    """
    Convert a pyGSTi outcome label of a circuit with mid-circuit measurements into a bitstring of the
    expanded (data + virtual qubits) system.

    pyGSTi outcome labels are tuples ``(mcm_1, ..., mcm_m, final)`` where each ``mcm_k`` is the member
    key of an instrument (here required to be a bitstring such as ``'0'`` or ``'01'``) and ``final`` is
    the terminating-measurement bitstring over the data qubits.  The returned bitstring is
    ``final + mcm_1 + ... + mcm_m``, i.e. data bits first followed by the MCM outcomes in MCM order,
    matching the line ordering of :func:`expand_mcm_circuit`.

    Parameters
    ----------
    outcome : tuple of str or str
        An outcome label.  A plain string (or length-1 tuple) is returned unchanged.

    Returns
    -------
    str
    """
    if isinstance(outcome, str):
        bits = outcome
    else:
        outcome = tuple(outcome)
        bits = outcome[-1] + ''.join(outcome[:-1])
    if not all(ch in '01' for ch in bits):
        raise ValueError(("Cannot interpret outcome label %s as a bitstring of the expanded system. "
                          "Instrument member keys must be bitstrings (e.g. '0'/'1').") % str(outcome))
    return bits


def joint_outcome_probabilities_to_bitstring_dict(prob_dict):
    """
    Re-key a ``{outcome_label: probability}`` dictionary by expanded-system bitstrings.

    Parameters
    ----------
    prob_dict : dict
        Dictionary (e.g. an :class:`OutcomeLabelDict` from :meth:`Model.probabilities`) whose keys are
        outcome labels of a circuit with (or without) mid-circuit measurements.

    Returns
    -------
    dict
        Maps bitstrings (see :func:`joint_outcome_to_bitstring`) to probabilities.
    """
    ret = {}
    for outcome, p in prob_dict.items():
        b = joint_outcome_to_bitstring(outcome)
        ret[b] = ret.get(b, 0.0) + p
    return ret


