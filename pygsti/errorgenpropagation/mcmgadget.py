#: Token used inside error-generator specifications (e.g. ``'XX:1,v'``) to denote the virtual qubit.
VIRTUAL_QUBIT_TOKEN = 'v'

#: Default instrument (gate) names that are interpreted as computational-basis mid-circuit measurements.
DEFAULT_MCM_GATE_NAMES = ('Iz',)

#: Bookkeeping record for one measured qubit of an MCM inside a circuit.
MCMInfo = _collections.namedtuple('MCMInfo', ['layer_index', 'component_index', 'mcm_index',
                                              'data_qubit', 'virtual_qubit'])
MCMInfo.__doc__ = """Describes a single measured qubit of a mid-circuit measurement in a circuit.

Attributes
----------
layer_index : int
    Index of the circuit layer containing the MCM.
component_index : int
    Index of the instrument label within that layer's components.
mcm_index : int
    Running index of this measured qubit among all MCMs of the circuit (0-based).  Virtual qubit
    number `mcm_index` is appended after the data qubits in the expanded circuit.
data_qubit : hashable
    Line label of the measured (data) qubit.
virtual_qubit : hashable
    Line label of the virtual qubit that stores the MCM outcome in the expanded circuit.
"""


