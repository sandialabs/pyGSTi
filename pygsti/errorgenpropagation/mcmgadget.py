# First-order crunch map, MCM gauge and FOMGI quantities
# ---------------------------------------------------------------------------------------------------

def mcm_crunch_matrix(errorgen_labels, num_gadget_data_qubits=1, measured_index=0):
    """
    Matrix of the first-order map from gadget error-generator rates to instrument deviations.

    Column ``j`` is the concatenation of ``vec(ΔQ_0)`` and ``vec(ΔQ_1)`` (row-major, pp basis) where
    ``ΔQ_c = (I ⊗ <<c|) L_j CNOT (I ⊗ |0>>)`` for the ``j``-th elementary error generator.  Its null space
    is the *MCM gauge* (gadget errors with no first-order effect on the instrument) and its row space
    spans the identifiable (FOMGI) combinations.

    Parameters
    ----------
    errorgen_labels : list
        Error generator specifications (see :func:`mcm_gadget_errorgen` for accepted formats).
    num_gadget_data_qubits : int, optional
    measured_index : int, optional

    Returns
    -------
    numpy.ndarray
        Shape ``(2 * 16**k, len(errorgen_labels))``.
    """
    cols = []
    for lbl in errorgen_labels:
        typ, bels = _normalize_errorgen_key(lbl)
        dev = mcm_gadget_crunch(elementary_errorgen_matrix(typ, bels, 'pp'), num_gadget_data_qubits, measured_index)
        cols.append(_np.concatenate([dev['0'].ravel(), dev['1'].ravel()]))
    F = _np.array(cols).T if len(cols) > 0 else _np.zeros((2 * 16**num_gadget_data_qubits, 0))
    return F.real if _np.allclose(F.imag, 0) else F


def mcm_gauge_directions(errorgen_labels, num_gadget_data_qubits=1, measured_index=0, tol=1e-10):
    """
    Orthonormal basis of the MCM gauge: combinations of gadget error generators with no first-order effect
    on the instrument.

    Parameters
    ----------
    errorgen_labels : list
    num_gadget_data_qubits : int, optional
    measured_index : int, optional
    tol : float, optional
        Singular values below `tol` are treated as zero.

    Returns
    -------
    numpy.ndarray
        Shape ``(len(errorgen_labels), gauge_dimension)``; each column is a null vector (coefficients
        indexed like `errorgen_labels`).
    """
    F = mcm_crunch_matrix(errorgen_labels, num_gadget_data_qubits, measured_index)
    return _spl.null_space(F, rcond=tol)


def mcm_identifiable_directions(errorgen_labels, num_gadget_data_qubits=1, measured_index=0, tol=1e-10):
    """
    Orthonormal basis of the row space of the crunch map: the first-order identifiable combinations of the
    given gadget error generators (the orthogonal complement of the MCM gauge).

    Returns
    -------
    numpy.ndarray
        Shape ``(len(errorgen_labels), rank)``.
    """
    F = mcm_crunch_matrix(errorgen_labels, num_gadget_data_qubits, measured_index)
    if F.shape[1] == 0:
        return _np.zeros((0, 0))
    return _spl.orth(F.T, rcond=tol)


#: Representative elementary error generators defining the 28 elementary instrument deviations
#: (FOMGI quantities) of Wysocki et al., arXiv:2602.03938, Tables 2-7, for the single-qubit MCM gadget
#: (first Pauli character = measured/data qubit, second = virtual qubit).  The deviation associated with
#: each name is the crunch of its representative generator; the deviations are linearly independent and span
#: the full 28-dimensional space of trace-preserving instrument deviations.
FOMGI_REPRESENTATIVES = _collections.OrderedDict([
    # Pauli-stochastic: depolarization during measurement / re-preparation, pure readout error
    ('s_meas', ('S', ('XX',))), ('s_prep', ('S', ('XI',))), ('s_read', ('S', ('IX',))),
    # Active: with S terms generate amplitude damping and measurement bias
    ('a_meas', ('A', ('XX', 'YX'))), ('a_prep', ('A', ('XI', 'YI'))), ('a_read', ('A', ('IX', 'IY'))),
    # Axis rotations (Hamiltonian)
    ('r_meas_x', ('H', ('XX',))), ('r_meas_y', ('H', ('YX',))),
    ('r_prep_x_ind', ('H', ('XI',))), ('r_prep_x_dep', ('H', ('XZ',))),
    ('r_prep_y_ind', ('H', ('YI',))), ('r_prep_y_dep', ('H', ('YZ',))),
    # rho-dependent axis rotations (correlation/active)
    ('rt_meas_x', ('C', ('XI', 'ZY'))), ('rt_meas_y', ('C', ('IX', 'XZ'))),
    ('rt_meas_xz', ('C', ('XZ', 'ZY'))), ('rt_meas_yz', ('C', ('IX', 'XI'))),
    ('rt_prep_x_ind', ('C', ('XX', 'ZY'))), ('rt_prep_x_dep', ('C', ('IX', 'XY'))),
    ('rt_prep_y_ind', ('C', ('IX', 'XX'))), ('rt_prep_y_dep', ('C', ('XX', 'ZX'))),
    # Unitary weakness (incomplete collapse; Hamiltonian)
    ('w0', ('H', ('ZY',))), ('w1', ('H', ('IY',))), ('w2', ('H', ('ZX',))), ('w3', ('H', ('IX',))),
    # Non-unitary weakness (correlation)
    ('wt0', ('C', ('XI', 'XY'))), ('wt1', ('C', ('XI', 'YY'))),
    ('wt2', ('C', ('YY', 'YZ'))), ('wt3', ('C', ('XX', 'XZ'))),
])

#: Sector ('H', 'S', 'C' or 'A') of each named FOMGI quantity, i.e. of its representative generator.
FOMGI_SECTORS = _collections.OrderedDict([(name, typ) for name, (typ, _) in FOMGI_REPRESENTATIVES.items()])


def fomgi_representatives(sectors=('H', 'S')):
    """
    The named FOMGI quantities whose representative generators lie in the given error generator sectors.

    Parameters
    ----------
    sectors : iterable of str or 'all', optional
        Error generator sectors to include (subset of ``('H', 'S', 'C', 'A')``).  With the default
        ``('H', 'S')`` this gives the 13 quantities identifiable from Hamiltonian and Pauli-stochastic
        gadget errors: ``s_meas, s_prep, s_read`` (S) and ``r_meas_x, r_meas_y, r_prep_{x,y}_{ind,dep},
        w0..w3`` (H).

    Returns
    -------
    OrderedDict
        Maps names to ``(errorgen_type, basis_element_labels)`` tuples.
    """
    if sectors == 'all':
        sectors = ('H', 'S', 'C', 'A')
    return _collections.OrderedDict([(name, rep) for name, rep in FOMGI_REPRESENTATIVES.items()
                                     if rep[0] in sectors])


def fomgi_ansatz(sectors=('H', 'S'), rates=None):
    """
    A gadget error model containing one representative generator per FOMGI quantity.

    Using this as the error model of an ``('Iz', q)`` entry in a linearized-GST ansatz gives a set of MCM
    parameters with no MCM-gauge redundancy whose estimated rates are directly the named FOMGI quantities.

    Parameters
    ----------
    sectors : iterable of str or 'all', optional
        See :func:`fomgi_representatives`.
    rates : dict, optional
        Maps FOMGI names to rates; missing names get rate 0.

    Returns
    -------
    OrderedDict
        Maps ``(errorgen_type, pauli_string[, pauli_string])`` keys to rates, in the format accepted as a
        value of the `lindblad_coeff` dictionaries used throughout :mod:`pygsti.algorithms.linearizedgst`.
    """
    rates = {} if rates is None else rates
    reps = fomgi_representatives(sectors)
    unknown = set(rates.keys()) - set(reps.keys())
    if unknown:
        raise ValueError("Unknown FOMGI quantity names (or names outside the requested sectors): %s" % str(unknown))
    return _collections.OrderedDict([((typ,) + tuple(bels), rates.get(name, 0.0))
                                     for name, (typ, bels) in reps.items()])


def fomgi_names_for_ansatz(errorgen_keys):
    """
    Map gadget error generator keys that are FOMGI representatives back to their FOMGI names.

    Parameters
    ----------
    errorgen_keys : iterable
        Error generator keys (see :func:`mcm_gadget_errorgen`).

    Returns
    -------
    dict
        Maps each key that is a representative generator to its FOMGI name.
    """
    lookup = {(typ, tuple(bels)): name for name, (typ, bels) in FOMGI_REPRESENTATIVES.items()}
    ret = {}
    for key in errorgen_keys:
        typ, bels = _normalize_errorgen_key(key)
        if (typ, tuple(bels)) in lookup:
            ret[key] = lookup[(typ, tuple(bels))]
    return ret


def fomgi_decomposition_matrix(errorgen_labels, sectors='auto', measured_index=0):
    """
    Matrix expressing the first-order instrument deviation of each single-qubit-gadget error generator in the
    basis of named FOMGI elementary deviations.

    If ``T`` is the returned matrix and ``eps`` a vector of rates for `errorgen_labels`, then ``T @ eps`` are
    the FOMGI quantities of the gadget error model ``sum_j eps_j L_j`` (to first order).

    Parameters
    ----------
    errorgen_labels : list
        Two-qubit gadget error generator specifications (measured qubit first, virtual qubit second).
    sectors : iterable of str, 'all' or 'auto', optional
        FOMGI quantities to decompose into (see :func:`fomgi_representatives`).  ``'auto'`` uses the 13
        H+S quantities when all `errorgen_labels` are of type 'H' or 'S' and all 28 quantities otherwise.
    measured_index : int, optional
        Index of the measured qubit within the gadget data qubits (only ``0`` is meaningful for the
        single-qubit gadget).

    Returns
    -------
    names : list of str
    T : numpy.ndarray
        Shape ``(len(names), len(errorgen_labels))``.
    """
    typs = [_normalize_errorgen_key(lbl)[0] for lbl in errorgen_labels]
    if sectors == 'auto':
        sectors = ('H', 'S') if all(t in ('H', 'S') for t in typs) else 'all'
    reps = fomgi_representatives(sectors)
    names = list(reps.keys())
    F_rep = mcm_crunch_matrix(list(reps.values()), 1, measured_index)
    F = mcm_crunch_matrix(errorgen_labels, 1, measured_index)
    T, residuals, rank, _ = _np.linalg.lstsq(F_rep, F, rcond=None)
    assert rank == len(names), "FOMGI representative deviations are unexpectedly linearly dependent!"
    if F.shape[1] > 0 and _np.linalg.norm(F_rep @ T - F) > 1e-8 * max(1.0, _np.linalg.norm(F)):
        _warnings.warn("Some of the given error generators produce instrument deviations outside the span of "
                       "the requested FOMGI sectors; consider sectors='all'.")
    T[_np.abs(T) < 1e-12] = 0.0
    return names, T


def fomgi_quantities(errorgen_rates, sectors='auto', measured_index=0):
    """
    The (first-order) FOMGI quantities of a single-qubit MCM gadget error model.

    Parameters
    ----------
    errorgen_rates : dict
        Gadget error generator rates (two-qubit Pauli strings: measured qubit, virtual qubit).
    sectors : iterable of str, 'all' or 'auto', optional
        See :func:`fomgi_decomposition_matrix`.
    measured_index : int, optional

    Returns
    -------
    OrderedDict
        Maps FOMGI names to values.
    """
    labels = list(errorgen_rates.keys())
    names, T = fomgi_decomposition_matrix(labels, sectors, measured_index)
    eps = _np.array([errorgen_rates[l] for l in labels], dtype=float)
    return _collections.OrderedDict(zip(names, (T @ eps) if len(labels) > 0 else _np.zeros(len(names))))


def all_gadget_errorgen_keys(sectors=('H', 'S'), num_gadget_data_qubits=1):
    """
    All elementary error generator keys of the requested sectors on the gadget space.

    Parameters
    ----------
    sectors : iterable of str, optional
    num_gadget_data_qubits : int, optional

    Returns
    -------
    list of tuple
        ``(type, pauli)`` tuples for 'H'/'S' and ``(type, pauli1, pauli2)`` tuples (``pauli1 < pauli2``
        lexicographically) for 'C'/'A'.
    """
    nq = num_gadget_data_qubits + 1
    paulis = [''.join(p) for p in _itertools.product('IXYZ', repeat=nq)][1:]  # drop identity
    keys = []
    for typ in sectors:
        if typ in ('H', 'S'):
            keys.extend([(typ, p) for p in paulis])
        elif typ in ('C', 'A'):
            keys.extend([(typ, p, q) for p, q in _itertools.combinations(paulis, 2)])
        else:
            raise ValueError("Unknown sector '%s'" % str(typ))
    return keys
