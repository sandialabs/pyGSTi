"""
Overview
--------
A noisy computational-basis mid-circuit measurement (MCM) of a qubit ``q`` is modelled, following
Wysocki et al. (arXiv:2602.03938), by a *circuit gadget* acting on the data qubits plus one
auxiliary *virtual* qubit ``v``:

1. ideal preparation of ``v`` in :math:`|0\\rangle`,
2. an ideal CNOT with ``q`` as control and ``v`` as target,
3. a post-CNOT error channel :math:`e^{L}` generated by a Lindbladian ``L`` on (data qubits + ``v``),
4. an ideal terminating Z-basis measurement of ``v``, whose result is the MCM outcome ``c``.

The resulting quantum instrument is :math:`Q_c = (I \\otimes \\langle\\langle c|) e^{L}
\\,\\mathrm{CNOT}\\,(I \\otimes |0\\rangle\\rangle)`, and to first order in the error rates the
*deviation* from the ideal projective instrument is the linear ("crunch") map
:math:`\\Delta Q_c = (I \\otimes \\langle\\langle c|) L \\,\\mathrm{CNOT}\\,(I \\otimes |0\\rangle\\rangle)`.

Because every ingredient of the gadget is a stabilizer operation, a circuit containing ``m``
MCMs on ``n`` qubits maps onto an ordinary *Clifford* circuit on ``n + m`` qubits in which each
MCM is replaced by a CNOT onto a fresh virtual qubit (this is just the deferred-measurement
principle).  The terminating computational-basis measurement of the enlarged circuit then
records the *joint* (final bitstring, MCM outcomes) distribution, and the existing error
generator propagation / first-order sensitivity machinery (:mod:`pygsti.tools.errgenproptools`)
can be applied to MCM circuits without modification.  This module provides:

* :func:`expand_mcm_circuit` -- the circuit-level gadget substitution,
* :func:`joint_outcome_to_bitstring` -- conversion of pyGSTi's MCM outcome tuples to bitstrings
  of the enlarged system,
* dense constructions of the gadget generator, the noisy instrument members and pyGSTi
  :class:`~pygsti.modelmembers.instruments.Instrument` objects (for simulation),
* the first-order crunch map, its null space (the *MCM gauge*) and the *first-order
  MCM-gauge-invariant (FOMGI)* quantities of Wysocki et al.

Conventions
-----------
* Gadget Pauli strings list the gadget's data qubit(s) first and the virtual qubit *last*; e.g. for
  the standard one-data-qubit gadget, ``'ZY'`` means ``Z`` on the measured qubit and ``Y`` on the
  virtual qubit (so ``S_IX`` is a pure readout error and ``H_ZY`` a "unitary weakness").
* Error generators use pyGSTi's conventions, ``H_P[rho] = -i[P, rho]`` and
  ``S_P[rho] = P rho P - rho`` with *unnormalized* Paulis, matching :class:`LindbladErrorgen`.
* Virtual qubits are appended after the data qubits, in MCM order (layer order first, then
  component order within a layer, then qubit order within a multi-qubit instrument label), which
  matches the ordering of instrument outcomes in pyGSTi outcome-label tuples.
"""

