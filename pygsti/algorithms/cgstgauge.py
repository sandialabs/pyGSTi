def _check_pp_basis(model):
    """Raise if `model` is not expressed in the normalized Pauli-product basis."""
    if model.basis.name != 'pp':
        raise ValueError("cGST gauge fixing assumes the normalized Pauli-product ('pp') basis, "
                         "but the model's basis is %s" % repr(model.basis.name))


def _resolve_gate_label(target_model, gate):
    """Resolve `gate` (a Label, tuple, or bare gate name) to a key of `target_model.operations`."""
    keys = list(target_model.operations.keys())
    if isinstance(gate, _Label):
        if gate in keys:
            return gate
    elif isinstance(gate, tuple):
        lbl = _Label(gate)
        if lbl in keys:
            return lbl
    elif isinstance(gate, str):
        if _Label(gate) in keys:
            return _Label(gate)
        matches = [k for k in keys if k.name == gate]
        if len(matches) == 1:
            return matches[0]
        if len(matches) > 1:
            raise ValueError("Gate name %s is ambiguous in the target model: %s" % (gate, matches))
    raise KeyError("Gate %s not found among the target model's operations %s" % (repr(gate), keys))


def _dense(op):
    return _np.asarray(op.to_dense(), dtype=float)


def _cluster_indices(values, tol):
    """
    Group the (complex) `values` into clusters of mutually close values.

    Returns a list of (representative value, list of indices), ordered by first appearance.
    """
    clusters = []
    for i, v in enumerate(values):
        for c in clusters:
            if abs(v - c[0]) <= tol:
                c[1].append(i)
                break
        else:
            clusters.append([v, [i]])
    return [(c[0], c[1]) for c in clusters]


def _spectral_projectors(mx, tol):
    """
    Eigen-decompose `mx` and return (cluster values, multiplicities, spectral projectors).

    The projectors P_c = V_c (V^{-1})_c project onto the (generalized) eigenspace of each
    cluster of eigenvalues along the others; they sum to the identity and P_c P_c' = 0.
    """
    evals, V = _np.linalg.eig(mx)
    cond = _np.linalg.cond(V)
    if not _np.isfinite(cond) or cond > 1e12:
        raise ValueError("Superoperator is not (numerically) diagonalizable: eigenvector matrix "
                         "condition number %g" % cond)
    Vinv = _np.linalg.inv(V)
    clusters = _cluster_indices(evals, tol)
    values = _np.array([c[0] for c in clusters])
    mults = [len(c[1]) for c in clusters]
    projs = [V[:, idx] @ Vinv[idx, :] for _, idx in clusters]
    return values, mults, projs, evals


def _commutator_map(G):
    """Matrix of K -> K G - G K acting on row-major vec(K)."""
    n = G.shape[0]
    return _np.kron(_np.identity(n), G.T) - _np.kron(G, _np.identity(n))


def _tp_row_constraints(n):
    """Rows selecting the first row of a row-major vectorized n x n matrix."""
    rows = _np.zeros((n, n * n))
    for j in range(n):
        rows[j, j] = 1.0
    return rows


def _orthonormal_complement(Q, m):
    """Orthonormal basis (columns) of the complement of span(Q) in R^m (Q may have 0 columns)."""
    if Q.shape[1] == 0:
        return _np.identity(m)
    return _spl.null_space(Q.T)


def _expm_combo(coeffs, mxs):
    n = mxs[0].shape[0] if len(mxs) > 0 else None
    if n is None or len(coeffs) == 0:
        return None
    K = _np.zeros((n, n))
    for c, M in zip(coeffs, mxs):
        K += c * M
    return _spl.expm(K)


def _least_squares(fun, x0, args=(), diff_step=None, jac='2-point'):
    """Wrapper choosing 'lm' when possible (needs #residuals >= #params)."""
    x0 = _np.asarray(x0, dtype=float)
    nres = fun(x0, *args).size
    method = 'lm' if nres >= x0.size else 'trf'
    return _spo.least_squares(fun, x0, args=args, method=method, jac=jac, xtol=1e-14, ftol=1e-14,
                              gtol=1e-14, max_nfev=2000, diff_step=diff_step)


