# stage 1: the commuting gauge
# ---------------------------------------------------------------------------

def commuting_gauge_transform(noisy_superop, ideal_superop, tol=1e-6):
    """
    Gauge transformation bringing a noisy gate to the *commuting gauge* of its ideal counterpart.

    This is the exact construction of the cGST manuscript's appendix "Construction of
    the commuting gauge".  Writing the noisy gate `Lam` and the ideal gate `G` in
    eigen-decomposed form, each noisy eigenvalue is paired with the ideal eigenvalue
    cluster it is closest to, and the transformation `A = W V^{-1}` maps the noisy
    eigenvectors `V` onto (ideal-eigenspace) vectors `W`, so that `A Lam A^{-1}` is
    block diagonal with respect to the spectral projectors of `G` and hence commutes
    with `G` *exactly*.

    The eigenvector normalizations are fixed canonically by choosing `W_c = P_c V_c`,
    where `P_c` is the ideal spectral projector of cluster `c`.  Equivalently

        A = sum_c P_c Pi_c,

    where `Pi_c` is the noisy spectral projector of cluster `c`.  This choice is
    basis free, makes `A` real automatically (conjugate clusters contribute conjugate
    terms), tends to the identity as the noise vanishes, and is trace preserving:
    since `<<I|` is an exact left fixed point of any TP `Lam`, it lies in the noisy
    cluster around the ideal eigenvalue 1, so `<<I| A = <<I| Pi_1 = <<I|`.  Within
    the near-degenerate cluster {1, lambda_1} of, e.g., the S gate this automatically
    pairs the exact unit eigenvalue with the identity direction; the noisy fixed point
    is mapped to its projection onto the ideal eigenvalue-1 eigenspace, which is what
    produces the active-error entry of the manuscript's commuting form.

    Parameters
    ----------
    noisy_superop : numpy.ndarray
        The noisy gate's superoperator (real, TP, in a basis whose first element is
        proportional to the identity, e.g. 'pp').

    ideal_superop : numpy.ndarray
        The ideal gate's superoperator in the same basis (diagonalizable; for a
        unitary gate it is orthogonal).

    tol : float, optional
        Tolerance used to identify degenerate ideal eigenvalues and to check trace
        preservation of the inputs.

    Returns
    -------
    numpy.ndarray
        The real gauge matrix `A`, with `A[0, :] = e_0`, such that
        `A @ noisy_superop @ inv(A)` commutes with `ideal_superop`.

    Raises
    ------
    ValueError
        If the noisy spectrum cannot be unambiguously assigned to the ideal eigenvalue
        clusters (noise too large), or if the construction fails to be real.
    """
    Lam = _np.asarray(noisy_superop, dtype=float)
    G = _np.asarray(ideal_superop, dtype=float)
    n = G.shape[0]
    if G.shape != (n, n) or Lam.shape != (n, n):
        raise ValueError("Superoperators must be square matrices of the same dimension")
    e0 = _np.zeros(n); e0[0] = 1.0
    if _np.linalg.norm(G[0, :] - e0) > tol or _np.linalg.norm(Lam[0, :] - e0) > tol:
        raise ValueError("commuting_gauge_transform expects trace-preserving superoperators "
                         "(first row equal to e_0) in a basis whose first element is the identity")

    mu, ideal_mults, P, _ = _spectral_projectors(G, tol)
    if len(mu) > 1:
        gaps = [abs(mu[i] - mu[j]) for i in range(len(mu)) for j in range(i)]
        min_gap = min(gaps)
    else:
        min_gap = _np.inf

    evals, V = _np.linalg.eig(Lam)
    condV = _np.linalg.cond(V)
    if not _np.isfinite(condV) or condV > 1e12:
        raise ValueError("Noisy superoperator is not (numerically) diagonalizable "
                         "(eigenvector condition number %g)" % condV)
    Vinv = _np.linalg.inv(V)

    # assign each noisy eigenvalue to the nearest ideal cluster
    dists = _np.abs(evals[:, None] - mu[None, :])
    assignment = _np.argmin(dists, axis=1)
    nearest = dists[_np.arange(n), assignment]
    if _np.any(nearest >= 0.5 * min_gap):
        bad = [(evals[k], mu[assignment[k]]) for k in range(n) if nearest[k] >= 0.5 * min_gap]
        raise ValueError("Cannot separate the noisy spectrum into the ideal eigenvalue clusters "
                         "(noise too large): eigenvalue(s) %s are not within half the smallest "
                         "ideal gap %g of their nearest ideal eigenvalue" % (bad, min_gap))
    counts = _np.bincount(assignment, minlength=len(mu))
    if any(int(c) != m for c, m in zip(counts, ideal_mults)):
        raise ValueError("Noisy eigenvalue clusters do not match the ideal multiplicities: "
                         "ideal eigenvalues %s have multiplicities %s but %s noisy eigenvalues "
                         "were assigned to them" % (mu, ideal_mults, list(counts)))

    A = _np.zeros((n, n), dtype=complex)
    for c in range(len(mu)):
        idx = _np.where(assignment == c)[0]
        Pi_c = V[:, idx] @ Vinv[idx, :]
        A += P[c] @ Pi_c

    if _np.max(_np.abs(A.imag)) > 1e-8:
        raise ValueError("Commuting-gauge transformation failed to be real (max imaginary part %g)"
                         % _np.max(_np.abs(A.imag)))
    A = A.real.copy()
    if _np.linalg.norm(A[0, :] - e0) > 1e-8:
        raise ValueError("Commuting-gauge transformation failed to be trace preserving")
    A[0, :] = e0  # snap away roundoff so the transformed model is exactly TP
    condA = _np.linalg.cond(A)
    if not _np.isfinite(condA) or condA > 1e12:
        raise ValueError("Commuting-gauge transformation is singular (condition number %g)" % condA)
    return A


# ---------------------------------------------------------------------------
# residual freedom: the TP commutant
# ---------------------------------------------------------------------------

def tp_commutant_basis(ideal_superop, tol=1e-8):
    """
    Real orthonormal basis of TP-compatible generators commuting with an ideal gate.

    These are the matrices `K` with vanishing first row (so that `expm(K)` has first
    row `e_0`, i.e. is a trace-preserving gauge transformation) satisfying
    `K G = G K`.  They generate the residual gauge freedom left after the reference
    gate has been brought to its commuting gauge.

    For a single-qubit pi/2 rotation such as the S gate this space is four
    dimensional and corresponds to the manuscript's residual transformations: an
    equatorial scale (A_1, xi), an axis scale and an axis shift (A_2, zeta and eta),
    and an equatorial rotation (A_3, psi).  For a reference gate with a degenerate
    nontrivial eigenvalue (e.g. a pi rotation) the commutant, and hence this basis,
    is larger.

    Parameters
    ----------
    ideal_superop : numpy.ndarray
        The ideal gate's superoperator.

    tol : float, optional
        Relative singular-value cutoff used to determine the null space.

    Returns
    -------
    list of numpy.ndarray
        Matrices `K_i`, orthonormal with respect to the Frobenius inner product.  The
        particular basis within the commutant is arbitrary (it is whatever the SVD
        returns).
    """
    G = _np.asarray(ideal_superop, dtype=float)
    n = G.shape[0]
    M = _np.vstack([_commutator_map(G), _tp_row_constraints(n)])
    ns = _spl.null_space(M, rcond=tol)
    return [ns[:, i].reshape(n, n) for i in range(ns.shape[1])]


